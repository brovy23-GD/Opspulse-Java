package com.rovy.opspulse;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.rovy.opspulse.domain.*;
import com.rovy.opspulse.repository.*;
import com.rovy.opspulse.service.*;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.transaction.annotation.Transactional;
import java.net.URI;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@SpringBootTest(properties = {
    "opspulse.monitor.enabled=true",
    "opspulse.monitor.failure-threshold=3",
    "opspulse.monitor.recovery-threshold=2",
    "opspulse.monitor.targets[0].service-key=mon-alert-test",
    "opspulse.monitor.targets[0].name=Alert Test HTTPS",
    "opspulse.monitor.targets[0].url=https://example.com/",
    "opspulse.monitor.interval-ms=3600000"
})
@AutoConfigureMockMvc
@Transactional
class AutomaticIncidentIntegrationTest {
    @Autowired MonitoringService monitoring;
    @Autowired ManagedServiceRepository services;
    @Autowired IncidentRepository incidents;
    @Autowired MockMvc mvc;
    @Autowired ObjectMapper mapper;
    @MockitoBean HttpHealthProbe probe;

    @Test
    void sustainedFailuresCreateOneAutoIncidentAndRecoveryClosesIt() throws Exception {
        when(probe.check(any(URI.class)))
          .thenReturn(new HttpHealthProbe.Result(false, 503, "HTTP 503"));
        for (int i = 0; i < 2; i++) monitoring.scheduledCheck();
        ManagedService service = services.findByServiceKeyIgnoreCase("mon-alert-test").orElseThrow();
        assertEquals(0, incidents.findByService_IdAndAutoGeneratedTrueAndStatusNot(service.getId(), IncidentStatus.RESOLVED).size());
        monitoring.scheduledCheck();
        assertEquals(1, incidents.findByService_IdAndAutoGeneratedTrueAndStatusNot(service.getId(), IncidentStatus.RESOLVED).size());
        monitoring.scheduledCheck();
        assertEquals(1, incidents.findByService_IdAndAutoGeneratedTrueAndStatusNot(service.getId(), IncidentStatus.RESOLVED).size(),
            "Further failed checks must not create duplicate open incidents");
        mvc.perform(get("/api/v1/dashboard")).andExpect(jsonPath("$.activeIncidents").value(1));

        String history = mvc.perform(get("/api/v1/services/" + service.getId() + "/incidents"))
            .andExpect(status().isOk()).andReturn().getResponse().getContentAsString();
        JsonNode rows = mapper.readTree(history);
        assertEquals(1, rows.size());
        assertTrue(rows.get(0).get("autoGenerated").asBoolean());
        assertEquals("HIGH", rows.get(0).get("severity").asText());

        when(probe.check(any(URI.class))).thenReturn(new HttpHealthProbe.Result(true, 200, "HTTP 200"));
        monitoring.scheduledCheck();
        assertEquals(1, incidents.findByService_IdAndAutoGeneratedTrueAndStatusNot(service.getId(), IncidentStatus.RESOLVED).size(),
            "One successful check must not close an incident prematurely");
        monitoring.scheduledCheck();
        assertEquals(0, incidents.findByService_IdAndAutoGeneratedTrueAndStatusNot(service.getId(), IncidentStatus.RESOLVED).size());
        mvc.perform(get("/api/v1/dashboard")).andExpect(jsonPath("$.activeIncidents").value(0));
        history = mvc.perform(get("/api/v1/services/" + service.getId() + "/incidents"))
            .andReturn().getResponse().getContentAsString();
        rows = mapper.readTree(history);
        assertEquals("RESOLVED", rows.get(0).get("status").asText());
        assertTrue(rows.get(0).hasNonNull("resolvedAt"));
        assertEquals(HealthState.HEALTHY, services.findByServiceKeyIgnoreCase("mon-alert-test").orElseThrow().getHealth());
    }

    @Test
    void manualIncidentsAreNeverResolvedByAutomaticRecovery() throws Exception {
        when(probe.check(any(URI.class))).thenReturn(new HttpHealthProbe.Result(true, 200, "HTTP 200"));
        monitoring.scheduledCheck();
        ManagedService service = services.findByServiceKeyIgnoreCase("mon-alert-test").orElseThrow();
        Incident manual = incidents.save(new Incident(service, "Operator investigation", Severity.CRITICAL));
        monitoring.scheduledCheck();
        assertEquals(IncidentStatus.OPEN, incidents.findById(manual.getId()).orElseThrow().getStatus());
        assertFalse(incidents.findById(manual.getId()).orElseThrow().isAutoGenerated());
    }
}
